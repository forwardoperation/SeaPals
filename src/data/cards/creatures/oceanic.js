function stageLabel(stage) {
  if (stage === "base") return "Base";
  if (stage === "stage1") return "Stage 1";
  return "Stage 2";
}

export const oceanicBaitballCards = baitballStageData.map((card, index) => ({
  id: card.id,
  name: card.name,
  kind: CardKind.CREATURE,
  category: CardCategory.FISH,
  zone: CreatureZone.OCEAN,
  class: CreatureClass.FISH,
  subtype: CreatureSubtype.BAITBALL,
  image: `/images/cards/ocean/${card.id}.png`,
  sortOrder: 700 + index,
  cost: { rp: card.rp },
  victoryPoints: card.vp,
  health: card.health,
  preyDensity: card.preyDensity,
  stage: card.stage === "base" ? 0 : card.stage === "stage1" ? 1 : 2,
  stageLabel: stageLabel(card.stage),
  tags: ["creature", "fish", "baitball", card.stage],
  playRequirements: [],
  specialRules: [baitballRule],
  passives: card.passives ?? [],
  onPlay: card.onPlay ?? [],
  actions: [],
  upgrade: card.nextCardId
    ? {
        canUpgrade: true,
        nextCardId: card.nextCardId,
        evolvesFrom: card.evolvesFrom ?? null,
        text: `Upgrade to ${card.name} ${
          card.stage === "base" ? "Stage 1" : "Stage 2"
        }.`,
      }
    : {
        canUpgrade: false,
        nextCardId: null,
        evolvesFrom: card.evolvesFrom ?? null,
      },
  set: { id: "oceanic", name: "Oceanic", collectorNumber: null, totalInSet: null },
}));

export const oceanicCreatureCards = oceanicCreatureData.map((card, index) => {
  const playRequirements = [
    ...(card.preyDensityRequirement != null
      ? [`Requires ${card.preyDensityRequirement} Prey Density.`]
      : []),
    ...(card.playRequirements ?? []),
  ];

  return {
    ...card,
    kind: CardKind.CREATURE,
    category: categoryByClass[card.class],
    zone: CreatureZone.OCEAN,
    subtype: CreatureSubtype.OCEANIC,
    image: imageByCardId[card.id] ?? `/images/cards/ocean/${card.id}.png`,
    sortOrder: 720 + index,
    cost: { rp: card.rp },
    victoryPoints: card.vp,
    defense: card.defense ? { dice: card.defense } : null,
    tags: [
      "creature",
      "oceanic",
      String(categoryByClass[card.class]),
      ...(card.family ? [String(card.family).toLowerCase()] : []),
    ],
    playRequirements,
    specialRules: card.specialRules ?? [],
    passives: card.passives ?? [],
    onPlay: card.onPlay ?? [],
    actions: card.actions ?? [],
    set: { id: "oceanic", name: "Oceanic", collectorNumber: null, totalInSet: null },
  };
});
